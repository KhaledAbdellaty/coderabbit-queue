#!/usr/bin/env bash
# Manage the repo's .coderabbit.yaml from editable settings kept in the
# coderabbit-queue config (so branches, filters and instructions are editable
# by command, and the file is always regenerated whole and valid).
#
# usage:
#   cr-config.sh show                         print the settings and the YAML they render
#   cr-config.sh set-branches staging,main    review PRs into these base branches (exact names)
#   cr-config.sh set-profile chill            quiet | chill | assertive
#   cr-config.sh set-incremental off          on | off  (off = no review on every push; ask with "full review")
#   cr-config.sh add-filter '!**/*.lock'      a path filter glob ('!' excludes)
#   cr-config.sh remove-filter '!**/*.lock'
#   cr-config.sh add-instruction 'backend/**' 'Every JE must balance.'   (replaces an existing path)
#   cr-config.sh remove-instruction 'backend/**'
#   cr-config.sh render [--write]             print the YAML, or write ./.coderabbit.yaml at the repo root
#
# Keys follow docs.coderabbit.ai/reference/configuration. base_branches are
# regexes matched without anchors, so names are written as ^name$.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
. "$HERE/lib.sh"
crq_require_config
CMD=${1:-show}; shift || true

python3 -I - "$(crq_cfg)" "$CMD" "$@" <<'PY'
import json, re, subprocess, sys
cfg_path, cmd, *args = sys.argv[1:]
cfg = json.load(open(cfg_path))
rc = cfg.setdefault("review_config", {
    "language": "en-US",
    "profile": "chill",
    "auto_incremental_review": False,
    "drafts": False,
    "base_branches": [cfg.get("base", "main")],
    "path_filters": ["!**/package-lock.json", "!**/yarn.lock", "!**/pnpm-lock.yaml"],
    "path_instructions": [],
    "chat_auto_reply": True,
})

def need(n):
    if len(args) < n:
        sys.exit(f"{cmd}: expected {n} argument(s)")

def q(s):  # YAML double-quoted scalar
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def render():
    out = [
        "# Generated by coderabbit-queue (cr-config.sh). Edit with cr-config.sh, not by hand,",
        "# or your edits are lost on the next render.",
        f"language: {q(rc['language'])}",
        "reviews:",
        f"  profile: {rc['profile']}",
        "  auto_review:",
        "    enabled: true",
        f"    auto_incremental_review: {str(rc['auto_incremental_review']).lower()}",
        f"    drafts: {str(rc['drafts']).lower()}",
        "    base_branches:",
        *[f"      - {q('^' + re.escape(b) + '$')}" for b in rc["base_branches"]],
    ]
    if rc["path_filters"]:
        out += ["  path_filters:", *[f"    - {q(f)}" for f in rc["path_filters"]]]
    if rc["path_instructions"]:
        out.append("  path_instructions:")
        for item in rc["path_instructions"]:
            out.append(f"    - path: {q(item['path'])}")
            out.append("      instructions: |")
            out += [f"        {line}" for line in item["instructions"].splitlines() or [""]]
    out += ["chat:", f"  auto_reply: {str(rc['chat_auto_reply']).lower()}", ""]
    return "\n".join(out)

changed = True
if cmd == "show":
    changed = False
    print(json.dumps(rc, indent=2)); print("---"); print(render())
elif cmd == "set-branches":
    need(1); rc["base_branches"] = [b.strip() for b in args[0].split(",") if b.strip()]
elif cmd == "set-profile":
    need(1)
    if args[0] not in ("quiet", "chill", "assertive"):
        sys.exit("profile must be quiet, chill or assertive")
    rc["profile"] = args[0]
elif cmd == "set-incremental":
    need(1)
    if args[0] not in ("on", "off"):
        sys.exit("set-incremental takes on or off")
    rc["auto_incremental_review"] = args[0] == "on"
elif cmd == "add-filter":
    need(1)
    if args[0] not in rc["path_filters"]:
        rc["path_filters"].append(args[0])
elif cmd == "remove-filter":
    need(1); rc["path_filters"] = [f for f in rc["path_filters"] if f != args[0]]
elif cmd == "add-instruction":
    need(2)
    rc["path_instructions"] = [i for i in rc["path_instructions"] if i["path"] != args[0]]
    rc["path_instructions"].append({"path": args[0], "instructions": args[1]})
elif cmd == "remove-instruction":
    need(1); rc["path_instructions"] = [i for i in rc["path_instructions"] if i["path"] != args[0]]
elif cmd == "render":
    changed = False
    text = render()
    if "--write" in args:
        root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()
        if not root:
            sys.exit("render --write must run inside the repository")
        open(f"{root}/.coderabbit.yaml", "w").write(text)
        print(f"wrote {root}/.coderabbit.yaml")
    else:
        print(text)
else:
    sys.exit(f"unknown command {cmd}; see the usage at the top of cr-config.sh")

if changed:
    json.dump(cfg, open(cfg_path, "w"), indent=2)
    print(f"saved. Run 'cr-config.sh render --write' to update .coderabbit.yaml")
PY
